const fs = require('fs');
const path = require('path');

const nodejsProjectRoot = path.join(__dirname, '..', 'nodejs-assets', 'nodejs-project');
const loaderFilePath = path.join(__dirname, '..', 'metro-nodejs-dev-loader.js');

/**
 * Recursively gets all file paths within a directory.
 */
const getAllFiles = (dirPath, arrayOfFiles = []) => {
  try {
    const files = fs.readdirSync(dirPath);
    files.forEach(file => {
      const fullPath = path.join(dirPath, file);
      if (fs.statSync(fullPath).isDirectory()) {
        getAllFiles(fullPath, arrayOfFiles);
      } else {
        // Use a relative path from the project root for the require statement
        const relativePath = path.relative(path.join(__dirname, '..'), fullPath);
        // Normalize for Metro (use forward slashes)
        arrayOfFiles.push(`./${relativePath.replace(/\\/g, '/')}`);
      }
    });
  } catch (e) {
    console.error(`[HMR-GEN] Failed to read directory: ${dirPath}`, e);
  }
  return arrayOfFiles;
};

console.log('[HMR-GEN] Generating metro-nodejs-dev-loader.js...');

const allNodeFiles = getAllFiles(nodejsProjectRoot);

// We create the content of the file that will be run by Metro.
// This file will contain only static `require` calls.
let fileContent = `
/**
 * THIS FILE IS AUTO-GENERATED by scripts/generate-hmr-loader.js. DO NOT EDIT.
 * It is a HACK to trick Metro into watching our Node.js backend files.
 * It should ONLY be imported in development mode (\`__DEV__\`).
 */

if (__DEV__) {
  try {
`;

// Add a require statement for each file.
// We are now using static strings, which Metro understands.
allNodeFiles.forEach(filePath => {
  // We exclude app.js from being required by Metro to avoid the dynamic require error.
  if (!filePath.endsWith('app.js')) {
    fileContent += `    require('${filePath}');\n`;
  }
});

fileContent += `
  } catch (e) {
    // It's okay if these fail. Their purpose is just to be watched.
  }
}
`;

fs.writeFileSync(loaderFilePath, fileContent, 'utf8');

console.log(`[HMR-GEN] Successfully generated loader with ${allNodeFiles.length} files watched.`);
console.log(`[HMR-GEN] You can now start your app.`);
